'''pmacctd for pyflow: the configuration files it needs, out of the settings, and the process itself'''

import ipaddress, os, re, signal, socket, subprocess
from urllib.parse import urlsplit
from wizzie.geoip import GEOIP_PRIMITIVES
from wizzie import localgeo

PLUGIN = "wdp"  # plugin instance name, shows in the logs and in writer_id
# pmacctd.conf line that holds the API key, as it is written to the log
APIKEY_LINE = re.compile(r"^(http_apikey\[[^]]*\]:).*$", re.M)


class PmacctdConfig:
    '''pmacctd.conf and, depending on the settings, pretag.map (direction out of LOCAL_NETWORKS),
    networks.lst (NET_FIELDS) and pcap_interfaces.map (several interfaces)'''

    def __init__(self, conf, local_geo=None):
        self.conf = conf
        self.local_geo = local_geo  # see localgeo.resolve(); None: resolved when the files are written
        self.logger = conf.logger
        config_dir = conf.config["config_dir"]
        self.conf_file = os.path.join(config_dir, "pmacctd.conf")
        self.pretag_file = os.path.join(config_dir, "pretag.map")
        self.networks_file = os.path.join(config_dir, "networks.lst")
        self.ifmap_file = os.path.join(config_dir, "pcap_interfaces.map")

    def write(self) -> str:
        '''Writes the files and returns the path of pmacctd.conf'''
        if self.local_geo is None:
            self.local_geo = localgeo.resolve(self.conf)
        files = self.render()
        os.makedirs(self.conf.config["config_dir"], exist_ok=True)
        for path, content in files.items():
            with open(path, "w") as f:
                f.write(content)
        self.logger.info(f"pmacctd configuration written to {self.conf.config['config_dir']}")
        for path in (self.conf_file, self.pretag_file):
            if path in files:
                content = APIKEY_LINE.sub(r"\1 <API_KEY>", files[path])
                self.logger.info(f"{os.path.basename(path)}:\n{content}")
        return self.conf_file

    def render(self) -> dict:
        '''Contents of the files, by path'''
        c = self.conf.config
        files = {}
        aggregate = c["aggregate"]
        local_networks = self.conf.items("local_networks")

        def add_primitive(name):
            nonlocal aggregate
            if not re.search(rf"(^|[ ,]){re.escape(name)}([ ,]|$)", aggregate):
                aggregate = f"{aggregate}, {name}"

        # --- aggregation: label (direction) and nets follow LOCAL_NETWORKS
        if local_networks:
            src_l = self.__bpf_nets("src", local_networks)
            dst_l = self.__bpf_nets("dst", local_networks)
            dst_local = dst_l
            if self.conf.is_true("local_multicast"):
                dst_local = f"{dst_l} or dst net 224.0.0.0/4 or dst host 255.255.255.255 or dst net ff00::/8"
            rules = [
                "! Generated by pyflow out of LOCAL_NETWORKS: direction from the point of view",
                "! of the local networks. The first matching rule wins.",
                f"set_label=direction%local  filter='({src_l}) and ({dst_local})'",
            ]
            if self.conf.is_true("local_multicast"):
                rules.append("set_label=direction%local  filter='ip6 and src net fe80::/10'")
            rules += [f"set_label=direction%out    filter='{src_l}'", f"set_label=direction%in     filter='{dst_l}'"]
            files[self.pretag_file] = "\n".join(rules) + "\n"
            add_primitive("label")

            if self.conf.is_true("net_fields"):
                nets = ["! Generated by pyflow out of LOCAL_NETWORKS"] + local_networks
                if self.conf.is_true("local_multicast"):
                    nets += ["224.0.0.0/4", "255.255.255.255/32", "fe80::/10", "ff00::/8"]
                files[self.networks_file] = "\n".join(nets) + "\n"
                add_primitive("src_net")
                add_primitive("dst_net")

        # --- aggregation: GeoIP fields, when there is a database
        if c["geoipv2_file"]:
            for field in self.conf.items("geoip_fields"):
                for primitive in GEOIP_PRIMITIVES[field]:
                    add_primitive(primitive)

        # --- pmacctd.conf
        lines = ["! Generated by pyflow", "daemonize: false"]
        if self.conf.is_true("debug"):
            lines.append("debug: true")

        interfaces = self.conf.items("pcap_interface")
        if c["pcap_savefile"]:
            lines.append(f"pcap_savefile: {c['pcap_savefile']}")
        elif len(interfaces) > 1:
            files[self.ifmap_file] = "".join(f"ifindex={i} ifname={name}\n" for i, name in enumerate(interfaces, 1))
            lines += [f"pcap_interfaces_map: {self.ifmap_file}", "pcap_ifindex: map"]
        else:
            lines.append(f"pcap_interface: {interfaces[0]}")
        pcap_filter = self.__pcap_filter()
        if pcap_filter:
            lines.append(f"pcap_filter: {pcap_filter}")
        lines.append(f"promisc: {self.__tf('promisc')}")
        lines.append(f"snaplen: {c['snaplen']}")

        if local_networks:
            lines += [f"pre_tag_map: {self.pretag_file}", "pre_tag_label_encode_as_map: true"]
            if self.conf.is_true("net_fields"):
                lines.append(f"networks_file: {self.networks_file}")
        if c["geoipv2_file"]:
            lines.append(f"geoipv2_file: {c['geoipv2_file']}")

        lines.append(f"classifier_num_roots: {c['classifier_num_roots']}")
        lines.append(f"classifier_max_flows: {c['classifier_max_flows']}")
        lines.append(f"classifier_proto_guess: {self.__tf('classifier_proto_guess')}")

        p = PLUGIN
        lines += [
            f"plugins: http[{p}]",
            f"aggregate[{p}]: {aggregate}",
            f"http_endpoint[{p}]: {c['http_endpoint']}",
            f"http_topic[{p}]: {c['events_topic']}",
            f"http_apikey[{p}]: {c['api_key']}",
            f"http_timeout[{p}]: {c['http_timeout']}",
            f"http_retries[{p}]: {c['http_retries']}",
            f"http_multi_values[{p}]: {c['http_multi_values']}",
        ]
        if c["cache_entries"]:
            lines.append(f"http_cache_entries[{p}]: {c['cache_entries']}")
        lines.append(f"http_refresh_time[{p}]: {c['refresh_time']}")
        lines.append(f"http_history[{p}]: {c['history']}")
        # set to empty, these disable what they drive
        for key, cfg_key in (("history_roundoff", "http_history_roundoff"), ("timestamp_field", "http_timestamp_field"),
                             ("event_source", "http_event_source"), ("event_type", "http_event_type"),
                             ("override_prefix", "http_override_prefix")):
            if c[key]:
                lines.append(f"{cfg_key}[{p}]: {c[key]}")
        if local_networks:
            lines.append(f"http_label_flatten[{p}]: true")
        if self.conf.is_true("class_split"):
            lines.append(f"http_class_split[{p}]: true")
        if self.conf.is_true("class_details"):
            lines.append(f"http_class_details[{p}]: true")
        if c["geoip_asn_file"]:
            lines.append(f"http_geoip_asn_file[{p}]: {c['geoip_asn_file']}")
        if c["geoipv2_file"] and "city" in self.conf.items("geoip_fields"):
            lines.append(f"http_geoip_city_file[{p}]: {c['geoipv2_file']}")
            lines.append(f"http_geoip_lang[{p}]: {c['geoip_lang']}")
        local_geo = self.local_geo or {}
        if local_networks and local_geo:
            lines.append(f"http_local_networks[{p}]: {', '.join(local_networks)}")
            for key in ("country", "asn", "as_org", "coords", "city", "region", "ip"):
                if key in local_geo:
                    lines.append(f"http_local_{key}[{p}]: {local_geo[key]}")

        if c["extra_config"]:
            lines += ["! EXTRA_CONFIG", c["extra_config"]]

        files[self.conf_file] = "\n".join(lines) + "\n"
        return files

    # Private

    def __tf(self, key):
        return "true" if self.conf.is_true(key) else "false"

    @staticmethod
    def __bpf_nets(direction, networks):
        '''"src net a or src net b"'''
        return " or ".join(f"{direction} net {net}" for net in networks)

    def __pcap_filter(self):
        '''What PCAP_FILTER asks for, minus our own traffic to the endpoint'''
        pcap_filter = self.conf.config["pcap_filter"] or ""
        if not self.conf.is_true("pcap_exclude_endpoint"):
            return pcap_filter
        endpoint = urlsplit(self.conf.config["http_endpoint"])
        host = endpoint.hostname or ""
        try:
            port = endpoint.port or (443 if endpoint.scheme == "https" else 80)
        except ValueError:
            port = 443 if endpoint.scheme == "https" else 80
        # by address: a name pmacctd can't resolve would make it drop the whole filter
        addrs = self.__resolve(host)
        if not addrs:
            self.logger.warning(f"can't resolve '{host}', traffic to HTTP_ENDPOINT is not excluded from the capture")
            return pcap_filter
        exclude = "not ((" + " or ".join(f"host {addr}" for addr in addrs) + f") and tcp port {port})"
        return f"({pcap_filter}) and {exclude}" if pcap_filter else exclude

    @staticmethod
    def __resolve(host):
        if not host:
            return []
        try:
            return [str(ipaddress.ip_address(host))]  # IPv4 or IPv6 literal
        except ValueError:
            pass
        try:
            return sorted({info[4][0] for info in socket.getaddrinfo(host, None)})
        except OSError:
            return []


class Pmacctd:
    '''The pmacctd process: started, signalled and stopped by pyflow, which waits for it'''

    def __init__(self, conf, conf_file):
        self.logger = conf.logger
        self.conf_file = conf_file
        self.process = None

    def start(self):
        self.process = subprocess.Popen(["pmacctd", "-f", self.conf_file])
        self.logger.info(f"pmacctd started (PID {self.process.pid})")

    def poll(self):
        '''Exit code once pmacctd has ended, None while it runs'''
        return self.process.poll() if self.process else None

    def reload_maps(self):
        '''pre_tag_map, networks_file and pcap_interfaces_map are read again (SIGUSR2)'''
        self.__signal(signal.SIGUSR2)

    def print_stats(self):
        '''pmacctd logs packets received and dropped on each interface (SIGUSR1)'''
        self.__signal(signal.SIGUSR1)

    def stop(self, timeout=10):
        '''SIGTERM, and SIGKILL if it is still there after timeout seconds. Returns the exit code'''
        if not self.process or self.process.poll() is not None:
            return self.poll()
        self.process.terminate()
        try:
            return self.process.wait(timeout)
        except subprocess.TimeoutExpired:
            self.logger.warning(f"pmacctd still running {timeout} s after SIGTERM, killing it")
            self.process.kill()
            return self.process.wait()

    # Private

    def __signal(self, signum):
        if self.process and self.process.poll() is None:
            self.process.send_signal(signum)
