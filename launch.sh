#!/bin/sh
#
# Wizzie launcher for pmacctd (Dockerfile.wizzie): writes pmacctd.conf, and
# pretag.map / networks.lst when LOCAL_NETWORKS is set, out of environment
# variables, then runs pmacctd. Variables are described in README-wizzie.md.

set -e

die() { echo "launch.sh: $*" >&2; exit 1; }
is_true() { case "$1" in [Tt]rue|TRUE|1|[Yy]es|YES) return 0 ;; *) return 1 ;; esac; }

# A complete configuration file wins over everything else
if [ -n "$PMACCTD_CONFIG_FILE" ]; then
  [ -r "$PMACCTD_CONFIG_FILE" ] || die "PMACCTD_CONFIG_FILE '$PMACCTD_CONFIG_FILE' can't be read"
  echo "launch.sh: using $PMACCTD_CONFIG_FILE as is"
  exec pmacctd -f "$PMACCTD_CONFIG_FILE"
fi

[ -n "$HTTP_ENDPOINT" ] || die "HTTP_ENDPOINT is required"
[ -n "$API_KEY" ] || die "API_KEY is required"
[ -n "$PCAP_INTERFACE" ] || [ -n "$PCAP_SAVEFILE" ] || die "PCAP_INTERFACE is required"

# ${VAR-default}: unset takes the default, set to empty disables the feature
CONFIG_DIR=${CONFIG_DIR:-/tmp/pmacct}
EVENTS_TOPIC=${EVENTS_TOPIC:-pmacct}
AGGREGATE=${AGGREGATE:-class, etype, src_mac, dst_mac, vlan, src_host, dst_host, src_port, dst_port, proto, tos, tcpflags}
REFRESH_TIME=${REFRESH_TIME:-60}
HISTORY=${HISTORY:-1m}
HISTORY_ROUNDOFF=${HISTORY_ROUNDOFF-m}
TIMESTAMP_FIELD=${TIMESTAMP_FIELD-timestamp}
EVENT_SOURCE=${EVENT_SOURCE-pmacct}
EVENT_TYPE=${EVENT_TYPE-pmacct_flow}
OVERRIDE_PREFIX=${OVERRIDE_PREFIX-pmacct_}
PROMISC=${PROMISC:-True}
SNAPLEN=${SNAPLEN:-700}
PCAP_FILTER=${PCAP_FILTER:-}
PCAP_EXCLUDE_ENDPOINT=${PCAP_EXCLUDE_ENDPOINT:-True}
LOCAL_NETWORKS=${LOCAL_NETWORKS:-}
LOCAL_MULTICAST=${LOCAL_MULTICAST:-True}
NET_FIELDS=${NET_FIELDS:-False}
CLASSIFIER_NUM_ROOTS=${CLASSIFIER_NUM_ROOTS:-512}
CLASSIFIER_MAX_FLOWS=${CLASSIFIER_MAX_FLOWS:-200000}
CLASSIFIER_PROTO_GUESS=${CLASSIFIER_PROTO_GUESS:-True}
CLASS_SPLIT=${CLASS_SPLIT:-True}
HTTP_TIMEOUT=${HTTP_TIMEOUT:-10}
HTTP_RETRIES=${HTTP_RETRIES:-3}
HTTP_MULTI_VALUES=${HTTP_MULTI_VALUES:-131072}
CACHE_ENTRIES=${CACHE_ENTRIES:-}
GEOIPV2_FILE=${GEOIPV2_FILE:-}
DEBUG=${DEBUG:-False}
EXTRA_CONFIG=${EXTRA_CONFIG:-}

mkdir -p "$CONFIG_DIR"
CONF="$CONFIG_DIR/pmacctd.conf"
PRETAG="$CONFIG_DIR/pretag.map"
NETWORKS="$CONFIG_DIR/networks.lst"
IFMAP="$CONFIG_DIR/pcap_interfaces.map"
P=wdp  # plugin instance name, shows in the logs and in writer_id

tf() { if is_true "$1"; then echo true; else echo false; fi; }

# Comma separated list to one item per line, blanks removed
items() { echo "$1" | tr ',' '\n' | sed 's/^[[:space:]]*//; s/[[:space:]]*$//' | grep -v '^$' || true; }

# "src net a or src net b" out of LOCAL_NETWORKS
bpf_nets() { items "$LOCAL_NETWORKS" | sed "s#^#$1 net #" | sed ':a;N;$!ba;s/\n/ or /g'; }

# --- packet filter: what the user asks for, minus our own traffic to the endpoint
filter="$PCAP_FILTER"
if is_true "$PCAP_EXCLUDE_ENDPOINT"; then
  hostport=${HTTP_ENDPOINT#*://}
  hostport=${hostport%%/*}
  case "$HTTP_ENDPOINT" in https://*) port=443 ;; *) port=80 ;; esac
  case "$hostport" in
    \[*\]:*) host=${hostport%%]*}; host=${host#[}; port=${hostport##*]:} ;;
    \[*\]) host=${hostport#[}; host=${host%]} ;;
    *:*) host=${hostport%:*}; port=${hostport##*:} ;;
    *) host=$hostport ;;
  esac
  # by address: a name pmacctd can't resolve would make it drop the whole filter
  case "$host" in
    *:*|*[0-9].[0-9]*[0-9]) addrs="host $host" ;;  # IPv6 or IPv4 literal
    *) addrs=$(getent ahosts "$host" 2>/dev/null | awk '{print $1}' | sort -u | sed 's/^/host /' | sed ':a;N;$!ba;s/\n/ or /g') ;;
  esac
  if [ -n "$addrs" ]; then
    exclude="not (($addrs) and tcp port $port)"
    if [ -n "$filter" ]; then filter="($filter) and $exclude"; else filter="$exclude"; fi
  else
    echo "launch.sh: WARNING: can't resolve '$host', traffic to HTTP_ENDPOINT is not excluded from the capture" >&2
  fi
fi

# --- aggregation: label (direction) and nets follow LOCAL_NETWORKS
aggregate="$AGGREGATE"
add_primitive() { echo "$aggregate" | grep -Eq "(^|[ ,])$1([ ,]|$)" || aggregate="$aggregate, $1"; }

if [ -n "$LOCAL_NETWORKS" ]; then
  src_l=$(bpf_nets src)
  dst_l=$(bpf_nets dst)
  dst_local="$dst_l"
  if is_true "$LOCAL_MULTICAST"; then
    dst_local="$dst_l or dst net 224.0.0.0/4 or dst host 255.255.255.255 or dst net ff00::/8"
  fi

  {
    echo "! Generated by launch.sh out of LOCAL_NETWORKS: direction from the point of view"
    echo "! of the local networks. The first matching rule wins."
    echo "set_label=direction%local  filter='($src_l) and ($dst_local)'"
    if is_true "$LOCAL_MULTICAST"; then
      echo "set_label=direction%local  filter='ip6 and src net fe80::/10'"
    fi
    echo "set_label=direction%out    filter='$src_l'"
    echo "set_label=direction%in     filter='$dst_l'"
  } > "$PRETAG"
  add_primitive label

  if is_true "$NET_FIELDS"; then
    {
      echo "! Generated by launch.sh out of LOCAL_NETWORKS"
      items "$LOCAL_NETWORKS"
      if is_true "$LOCAL_MULTICAST"; then
        printf '224.0.0.0/4\n255.255.255.255/32\nfe80::/10\nff00::/8\n'
      fi
    } > "$NETWORKS"
    add_primitive src_net
    add_primitive dst_net
  fi
fi

# --- pmacctd.conf
{
  echo "! Generated by launch.sh"
  echo "daemonize: false"
  if is_true "$DEBUG"; then echo "debug: true"; fi

  if [ -n "$PCAP_SAVEFILE" ]; then
    echo "pcap_savefile: $PCAP_SAVEFILE"
  elif [ "$(items "$PCAP_INTERFACE" | wc -l)" -gt 1 ]; then
    i=0
    items "$PCAP_INTERFACE" | while read -r ifname; do
      i=$((i + 1))
      echo "ifindex=$i ifname=$ifname"
    done > "$IFMAP"
    echo "pcap_interfaces_map: $IFMAP"
    echo "pcap_ifindex: map"
  else
    echo "pcap_interface: $(items "$PCAP_INTERFACE")"
  fi
  [ -n "$filter" ] && echo "pcap_filter: $filter"
  echo "promisc: $(tf "$PROMISC")"
  echo "snaplen: $SNAPLEN"

  if [ -n "$LOCAL_NETWORKS" ]; then
    echo "pre_tag_map: $PRETAG"
    echo "pre_tag_label_encode_as_map: true"
    if is_true "$NET_FIELDS"; then echo "networks_file: $NETWORKS"; fi
  fi
  [ -n "$GEOIPV2_FILE" ] && echo "geoipv2_file: $GEOIPV2_FILE"

  echo "classifier_num_roots: $CLASSIFIER_NUM_ROOTS"
  echo "classifier_max_flows: $CLASSIFIER_MAX_FLOWS"
  echo "classifier_proto_guess: $(tf "$CLASSIFIER_PROTO_GUESS")"

  echo "plugins: http[$P]"
  echo "aggregate[$P]: $aggregate"
  echo "http_endpoint[$P]: $HTTP_ENDPOINT"
  echo "http_topic[$P]: $EVENTS_TOPIC"
  echo "http_apikey[$P]: $API_KEY"
  echo "http_timeout[$P]: $HTTP_TIMEOUT"
  echo "http_retries[$P]: $HTTP_RETRIES"
  echo "http_multi_values[$P]: $HTTP_MULTI_VALUES"
  [ -n "$CACHE_ENTRIES" ] && echo "http_cache_entries[$P]: $CACHE_ENTRIES"
  echo "http_refresh_time[$P]: $REFRESH_TIME"
  echo "http_history[$P]: $HISTORY"
  [ -n "$HISTORY_ROUNDOFF" ] && echo "http_history_roundoff[$P]: $HISTORY_ROUNDOFF"
  [ -n "$TIMESTAMP_FIELD" ] && echo "http_timestamp_field[$P]: $TIMESTAMP_FIELD"
  [ -n "$EVENT_SOURCE" ] && echo "http_event_source[$P]: $EVENT_SOURCE"
  [ -n "$EVENT_TYPE" ] && echo "http_event_type[$P]: $EVENT_TYPE"
  [ -n "$OVERRIDE_PREFIX" ] && echo "http_override_prefix[$P]: $OVERRIDE_PREFIX"
  [ -n "$LOCAL_NETWORKS" ] && echo "http_label_flatten[$P]: true"
  if is_true "$CLASS_SPLIT"; then echo "http_class_split[$P]: true"; fi

  if [ -n "$EXTRA_CONFIG" ]; then
    echo "! EXTRA_CONFIG"
    printf '%s\n' "$EXTRA_CONFIG"
  fi
} > "$CONF"

echo "launch.sh: configuration written to $CONFIG_DIR"
sed 's/^\(http_apikey\[[^]]*\]:\).*/\1 <API_KEY>/' "$CONF"
[ -f "$PRETAG" ] && [ -n "$LOCAL_NETWORKS" ] && cat "$PRETAG"

exec pmacctd -f "$CONF"
